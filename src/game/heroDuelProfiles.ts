export function getHeroDuelProfile(hero: General): HeroDuelProfile {
  const existing = HERO_DUEL_PROFILES[hero.id];
  if (existing) return existing;

  const pal = FACTION_DEFAULT_ARMOR[hero.faction] || FACTION_DEFAULT_ARMOR.neutral;
  const isStrategist = hero.archetype === 'strategist' || hero.archetype === 'statesman';

  return {
    heroId: hero.id,
    weaponClass: isStrategist ? 'fan' : hero.archetype === 'marshal' ? 'jian' : 'spear',
    weaponVariant: isStrategist
      ? 'feather_fan'
      : hero.archetype === 'marshal'
        ? 'imperial_jian'
        : 'dragon_lance',
    weaponWeight: isStrategist ? 'light' : 'heavy',
    weaponColor: '#e2e8f0',
    tasselColor: pal.aura,
    headgear: isStrategist ? 'scholar_crown' : 'crested_helm',
    isScholarRobe: isStrategist,
    armorPrimary: pal.primary,
    armorTrim: pal.trim,
    capeColor: pal.cape,
    auraColor: pal.aura,
    horseCoat: isStrategist ? 'dapple_grey' : 'imperial_bay',
    horseName: { en: 'Warhorse', zh: '战马' },
    bardingColor: pal.barding,
  };
}
